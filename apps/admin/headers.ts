/**
 * Cloudflare Pages `_headers` of the admin app (WP5-29), built from the build-time env so the CSP names exact origins.
 * No wildcard, no 'unsafe-*', no third-party host that is not in the env. Used by the Vite plugin in vite.config.ts
 * and by headers tests / the production check.
 */

/** Env names whose origin the browser has to reach (connect-src), see src/env.ts. */
export const CONNECT_ENV = ['VITE_SUPABASE_URL', 'VITE_API_BASE_URL', 'VITE_PUBLIC_SITE_URL', 'VITE_R2_UPLOAD_ORIGIN'] as const;
/** Env names whose origin serves photos (img-src). */
export const IMG_ENV = ['VITE_IMG_BASE_URL'] as const;

type Raw = Record<string, string | undefined>;

/** Origin of an http(s) URL, or null when the value is empty / not an http(s) URL. */
export function originOf(value: string | undefined): string | null {
  const v = (value ?? '').trim();
  if (v === '') return null;
  try {
    const u = new URL(v);
    return u.protocol === 'https:' || u.protocol === 'http:' ? u.origin : null;
  } catch {
    return null;
  }
}

function origins(raw: Raw, names: readonly string[]): string[] {
  return [...new Set(names.map((n) => originOf(raw[n])).filter((o): o is string => o !== null))];
}

export interface HeadersResult {
  text: string;
  csp: string;
  connectOrigins: string[];
  imgOrigins: string[];
}

export function buildCsp(raw: Raw): { csp: string; connectOrigins: string[]; imgOrigins: string[] } {
  const connectOrigins = origins(raw, CONNECT_ENV);
  const imgOrigins = origins(raw, IMG_ENV);
  const directives = [
    "default-src 'none'",
    "script-src 'self'",
    "style-src 'self'",
    `img-src ${["'self'", 'blob:', 'data:', ...imgOrigins].join(' ')}`,
    // Nothing else is ever requested from script: Supabase, the Worker API, the public site's /_publish.json and the R2 upload origin.
    `connect-src ${connectOrigins.length > 0 ? connectOrigins.join(' ') : "'none'"}`,
    "base-uri 'none'",
    "form-action 'self'",
    "frame-ancestors 'none'",
    "object-src 'none'",
  ];
  return { csp: directives.join('; '), connectOrigins, imgOrigins };
}

export function buildHeaders(raw: Raw): HeadersResult {
  const { csp, connectOrigins, imgOrigins } = buildCsp(raw);
  const text = [
    '# Generated by apps/admin/headers.ts at build time from the VITE_* origins. Do not edit by hand.',
    '/*',
    `  Content-Security-Policy: ${csp}`,
    '  X-Content-Type-Options: nosniff',
    '  Referrer-Policy: no-referrer',
    '  X-Frame-Options: DENY',
    '  X-Robots-Tag: noindex, nofollow',
    '  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=()',
    '  Cross-Origin-Opener-Policy: same-origin',
    '',
    '/assets/*',
    '  Cache-Control: public, max-age=31536000, immutable',
    '',
    '/index.html',
    '  Cache-Control: no-cache',
    '',
    '/',
    '  Cache-Control: no-cache',
    '',
  ].join('\n');
  return { text, csp, connectOrigins, imgOrigins };
}
