  '-- Order (foreign keys): categories, albums, photos, url_history, then one cover update.',
  '-- albums.cover_photo_id points at photos, so albums are inserted without a cover and the cover is',
  '-- set at the end, after the photos exist.',
  '--',
  '-- Triggers: every catalog table carries user triggers (updated_at stamps, the pending-changes counter,',
