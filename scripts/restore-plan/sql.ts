  '-- the insert-time bump_pending triggers and the updated_at stamp on albums (hit by the cover update).',
  '--',
  '--   drop trigger categories_bump_pending on public.categories;',
  '--   drop trigger albums_bump_pending on public.albums;',
  '--   drop trigger photos_bump_pending on public.photos;',
  '--   drop trigger url_history_bump_pending on public.url_history;',
  '--   drop trigger albums_set_updated_at on public.albums;',
  '--   -- ... run the inserts and the cover update below, then recreate exactly as migration',
  '--   -- 20261019100300_triggers.sql defines them:',
  '--   create trigger categories_bump_pending after insert or update or delete on public.categories',
  '--     for each row execute function public.bump_pending();',
  '--   create trigger albums_bump_pending after insert or update or delete on public.albums',
  '--     for each row execute function public.bump_pending();',
