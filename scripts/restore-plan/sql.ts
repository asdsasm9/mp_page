/** Deterministic SQL for a validated backup document. Same document in, same text out. */
export function emitRestoreSql(doc: BackupDocument): string {
  const out: string[] = [...HEADER, '', 'begin;', ''];

  for (const table of CATALOG_TABLES) out.push('alter table ' + table + ' disable trigger user;');
  out.push('');

  out.push(...insertStatement<Category>(TABLE_CATEGORIES, CATEGORY_COLUMNS, byId(doc.categories)), '');
  out.push(...insertStatement<Album>(TABLE_ALBUMS, ALBUM_COLUMNS, byId(doc.albums)), '');
  out.push(...insertStatement<Photo>(TABLE_PHOTOS, PHOTO_COLUMNS, byId(doc.photos)), '');
  out.push(...insertStatement<UrlHistory>(TABLE_URL_HISTORY, URL_HISTORY_COLUMNS, byId(doc.urlHistory)), '');

  const covered = byId(doc.albums).filter((a) => a.cover_photo_id !== null);
  if (covered.length === 0) out.push('-- covers: none to set');
  for (const album of covered) {
    out.push(
      'update ' + TABLE_ALBUMS + ' set cover_photo_id = ' + sqlLiteral(album.cover_photo_id) +
        ' where id = ' + sqlLiteral(album.id) + ' and cover_photo_id is null;',
    );
  }
  out.push('');

  for (const table of CATALOG_TABLES) out.push('alter table ' + table + ' enable trigger user;');
  out.push('');

  out.push('update public.site_state set pending_changes = greatest(pending_changes, 1);', '', 'commit;', '');
  return out.join('\n');
}
